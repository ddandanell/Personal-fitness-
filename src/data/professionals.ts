export function getProfessional(slug: string) {
  return professionals.find((item) => item.slug === slug)
}

export function professionalsFor(filter: { service?: string; city?: City; area?: string }) {
  return professionals.filter((person) => {
    if (filter.service && !person.services.includes(filter.service)) return false
    if (filter.city && !person.cities.includes(filter.city)) return false
    if (filter.area && !person.areas.includes(filter.area)) return false
    return true
  })
}
